#!/usr/bin/env bash
#
# wizard-flash-all.sh — Flash all 10 ESP32-S3 nodes sequentially
#
# Usage:
#   git clone https://github.com/belikh/aquila-v2-spec.git
#   cd aquila-v2-spec
#   . ~/esp/esp-idf/export.sh
#   bash scripts/wizard-flash-all.sh
#
# For each node (0-9):
#   1. Rebuilds firmware with that node ID
#   2. Detects serial port
#   3. Flashes the node
#   4. Asks you to unplug and plug in the next node
#
# Australian English spelling throughout.
#
# Prerequisites:
#   - ESP-IDF v5.5.2 installed and exported (`. ~/esp/esp-idf/export.sh`)
#   - One ESP32-S3 connected at a time
#
set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

info()  { printf "${BLUE}[info]${NC}  %s\n" "$*"; }
ok()    { printf "${GREEN}[ok]${NC}   %s\n" "$*"; }
warn()  { printf "${YELLOW}[warn]${NC} %s\n" "$*"; }
err()   { printf "${RED}[error]${NC}%s\n" "$*" >&2; }

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
require_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    err "Required command not found: $1"
    return 1
  }
}

detect_ports() {
  # Returns newline-separated list of candidate serial ports
  local ports=()
  mapfile -t _p < <(compgen -G '/dev/ttyUSB*' 2>/dev/null || true)
  ports+=("${_p[@]}")
  mapfile -t _p < <(compgen -G '/dev/ttyACM*' 2>/dev/null || true)
  ports+=("${_p[@]}")
  mapfile -t _p < <(compgen -G '/dev/cu.usbserial*' 2>/dev/null || true)
  ports+=("${_p[@]}")
  mapfile -t _p < <(compgen -G '/dev/cu.usbmodem*' 2>/dev/null || true)
  ports+=("${_p[@]}")
  # Deduplicate, preserve order
  local seen=()
  local result=()
  for p in "${ports[@]}"; do
    local found=0
    for s in "${seen[@]}"; do
      if [[ "$s" == "$p" ]]; then found=1; break; fi
    done
    if [[ $found -eq 0 ]]; then
      seen+=("$p")
      result+=("$p")
    fi
  done
  printf '%s\n' "${result[@]}"
}

press_enter() {
  read -rp "Press Enter when ready..." _
}

# ---------------------------------------------------------------------------
# Step 0: Prerequisites
# ---------------------------------------------------------------------------
step0_check() {
  info "Step 0 — Checking ESP-IDF toolchain"
  require_cmd idf.py || {
    err "idf.py not found. Export ESP-IDF first:"
    info "  . ~/esp/esp-idf/export.sh"
    exit 1
  }
  require_cmd python3
  ok "idf.py: $(command -v idf.py)"
  idf.py --version 2>/dev/null | head -1 || true
}

# ---------------------------------------------------------------------------
# Step 1: Collect configuration (shared across all nodes)
# ---------------------------------------------------------------------------
step1_config() {
  info "Step 1 — Configuration (shared across all 10 nodes)"
  read -rp "WiFi SSID: " WIFI_SSID
  read -rsp "WiFi password: " WIFI_PASSWORD
  printf "\n"
  read -rp "Core host IP (this laptop, e.g. 192.168.1.42): " CORE_HOST
  read -rp "Core data port [9100]: " CORE_DATA_PORT
  CORE_DATA_PORT="${CORE_DATA_PORT:-9100}"
  read -rp "Core control port [9101]: " CORE_CONTROL_PORT
  CORE_CONTROL_PORT="${CORE_CONTROL_PORT:-9101}"
  read -rp "Channel [6]: " CHANNEL
  CHANNEL="${CHANNEL:-6}"
  read -rp "Bandwidth MHz [20]: " BANDWIDTH_MHZ
  BANDWIDTH_MHZ="${BANDWIDTH_MHZ:-20}"

  ok "Configuration collected."
}

# ---------------------------------------------------------------------------
# Step 2: Write sdkconfig.defaults for a given node ID
# ---------------------------------------------------------------------------
write_sdkconfig() {
  local node_id="$1"
  local firmware_dir
  firmware_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/firmware/esp32-s3-csi-node"

  cat > "$firmware_dir/sdkconfig.defaults" <<EOF
# Aquila ESP32-S3 CSI node — generated by wizard-flash-all.sh
# Node ID: $node_id
# Do not edit by hand; re-run the wizard to change.

CONFIG_AQUILA_WIFI_SSID="$WIFI_SSID"
CONFIG_AQUILA_WIFI_PASSWORD="$WIFI_PASSWORD"
CONFIG_AQUILA_CORE_HOST="$CORE_HOST"
CONFIG_AQUILA_CORE_DATA_PORT=$CORE_DATA_PORT
CONFIG_AQUILA_CORE_CONTROL_PORT=$CORE_CONTROL_PORT
CONFIG_AQUILA_NODE_ID=$node_id
CONFIG_AQUILA_PAIRING_CODE=0
CONFIG_AQUILA_CHANNEL=$CHANNEL
CONFIG_AQUILA_BANDWIDTH_MHZ=$BANDWIDTH_MHZ
EOF
}

# ---------------------------------------------------------------------------
# Step 3: Build firmware for a node ID
# ---------------------------------------------------------------------------
step_build_node() {
  local node_id="$1"
  local firmware_dir
  firmware_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/firmware/esp32-s3-csi-node"

  info "Building firmware for node $node_id..."
  write_sdkconfig "$node_id"
  (cd "$firmware_dir" && idf.py set-target esp32s3)
  (cd "$firmware_dir" && idf.py reconfigure)
  (cd "$firmware_dir" && idf.py build)
  ok "Firmware for node $node_id built."
}

# ---------------------------------------------------------------------------
# Step 4: Flash one node
# ---------------------------------------------------------------------------
step_flash_node() {
  local node_id="$1"
  local firmware_dir
  firmware_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/firmware/esp32-s3-csi-node"

  info "Detecting serial port..."
  mapfile -t PORTS < <(detect_ports)

  if [[ ${#PORTS[@]} -eq 0 ]]; then
    err "No serial port detected."
    info "Plug in node $node_id and press Enter."
    press_enter
    mapfile -t PORTS < <(detect_ports)
    if [[ ${#PORTS[@]} -eq 0 ]]; then
      err "Still no serial port detected."
      return 1
    fi
  fi

  if [[ ${#PORTS[@]} -eq 1 ]]; then
    PORT="${PORTS[0]}"
  else
    info "Multiple ports detected:"
    local i=1
    for p in "${PORTS[@]}"; do
      printf "  %d) %s\n" "$i" "$p"
      i=$((i + 1))
    done
    read -rp "Select port number [1]: " choice
    choice="${choice:-1}"
    if [[ ! "$choice" =~ ^[0-9]+$ ]] || [[ "$choice" -lt 1 ]] || [[ "$choice" -gt ${#PORTS[@]} ]]; then
      err "Invalid selection."
      return 1
    fi
    PORT="${PORTS[$((choice - 1))]}"
  fi

  ok "Using port: $PORT"

  info "Flashing node $node_id..."
  info "If flash fails, put node in bootloader mode (hold GPIO0, press RESET, release GPIO0)."
  press_enter

  (cd "$firmware_dir" && idf.py -p "$PORT" flash)
  ok "Node $node_id flashed to $PORT."
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
main() {
  clear 2>/dev/null || true
  echo "=============================================="
  echo "  Aquila ESP32-S3 — Flash All 10 Nodes"
  echo "  Sequential flashing wizard"
  echo "=============================================="
  echo
  info "This script will flash 10 nodes sequentially, one at a time."
  info "Each node gets a unique node ID (0-9)."
  echo

  step0_check
  step1_config

  local firmware_dir
  firmware_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/firmware/esp32-s3-csi-node"

  for node_id in $(seq 0 9); do
    echo
    echo "----------------------------------------------"
    info "Node $node_id of 10"
    echo "----------------------------------------------"

    # Build firmware for this node ID
    step_build_node "$node_id"

    # Prompt user to plug in the node
    info "Plug in ESP32-S3 node $node_id."
    press_enter

    # Flash
    step_flash_node "$node_id"

    if [[ "$node_id" -lt 9 ]]; then
      info "Node $node_id flashed successfully."
      read -rp "Unplug node $node_id and plug in node $((node_id + 1)), then press Enter..." _
    fi
  done

  echo
  echo "=============================================="
  ok "All 10 nodes flashed."
  echo "=============================================="
  echo
  info "Node IDs 0-9 have been assigned."
  info "Node configuration:"
  info "  SSID: $WIFI_SSID"
  info "  Core host: $CORE_HOST:$CORE_DATA_PORT (data) / $CORE_CONTROL_PORT (control)"
  echo
  info "To run the full experiment suite once all nodes are deployed:"
  info "  cd docs/research/v2/experiments && python3 test_protocol_runner.py"
  echo
}

main "$@"