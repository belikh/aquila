//! The `node_wire.h` generator (`capture-and-firmware.md` §9.4).
//!
//! `aquila-wire` owns the one on-air layout; the firmware's C `node_wire`
//! component must implement the same layout. [`generate_c_header`] is a pure
//! function that renders the layout's constants and fixed structs as a C header
//! so the two ends cannot silently drift. CI can regenerate the header and diff
//! it against the committed copy.
//!
//! Scope: the fixed header and body fields, the magics, versions, ports, size
//! limits and opcodes are emitted, with `_Static_assert`s pinning the struct
//! sizes. The variable interleaved `int8` I/Q sample is reached through the
//! emitted offset macros, not a fixed C array member; emitting a full
//! variable-length struct is a documented gap to be closed with the firmware
//! component.

use core::fmt::Write as _;

use crate::constants::{
    control_offset, csi_body_offset, csi_offset, Opcode, CONTROL_AUTH_LEN, CONTROL_MAGIC,
    CONTROL_PORT, CSI_BODY_FIXED_LEN, CSI_DATA_PORT, CSI_FLAG_FIRST_WORD_INVALID, CSI_HEADER_LEN,
    CSI_MAGIC, CSI_MESSAGE_TYPE, MAX_DATAGRAM_LEN, MAX_SUBCARRIERS, OTA_DEFAULT_CHUNK_SIZE,
    OTA_DEFAULT_WINDOW, OTA_MAX_CHUNK_SIZE, SUBCARRIER_FORMAT_INT8_IQ, WIRE_MAJOR, WIRE_MINOR,
};

/// Render the canonical layout as a C header (`node_wire.h`).
///
/// The result is deterministic: identical constants always produce identical
/// bytes.
#[must_use]
pub fn generate_c_header() -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "/* Generated by aquila-wire::generate_c_header(). Do not edit. */"
    );
    let _ = writeln!(s, "#ifndef AQUILA_NODE_WIRE_H");
    let _ = writeln!(s, "#define AQUILA_NODE_WIRE_H");
    let _ = writeln!(s);
    let _ = writeln!(s, "#include <stdint.h>");
    let _ = writeln!(s, "#include <stddef.h>");
    let _ = writeln!(s);

    let _ = writeln!(s, "/* Versions and magics. */");
    let _ = writeln!(s, "#define AQ_WIRE_MAJOR {WIRE_MAJOR}u");
    let _ = writeln!(s, "#define AQ_WIRE_MINOR {WIRE_MINOR}u");
    emit_magic(&mut s, "AQ_CSI_MAGIC", CSI_MAGIC);
    emit_magic(&mut s, "AQ_CONTROL_MAGIC", CONTROL_MAGIC);
    let _ = writeln!(s, "#define AQ_CSI_MESSAGE_TYPE {CSI_MESSAGE_TYPE}u");
    let _ = writeln!(
        s,
        "#define AQ_SUBCARRIER_FORMAT_INT8_IQ {SUBCARRIER_FORMAT_INT8_IQ}u"
    );
    let _ = writeln!(
        s,
        "#define AQ_CSI_FLAG_FIRST_WORD_INVALID {CSI_FLAG_FIRST_WORD_INVALID}u"
    );
    let _ = writeln!(s);

    let _ = writeln!(s, "/* Ports and size limits. */");
    let _ = writeln!(s, "#define AQ_CSI_DATA_PORT {CSI_DATA_PORT}u");
    let _ = writeln!(s, "#define AQ_CONTROL_PORT {CONTROL_PORT}u");
    let _ = writeln!(s, "#define AQ_CSI_HEADER_LEN {CSI_HEADER_LEN}u");
    let _ = writeln!(s, "#define AQ_CSI_BODY_FIXED_LEN {CSI_BODY_FIXED_LEN}u");
    let _ = writeln!(s, "#define AQ_CSI_MAX_SUBCARRIERS {MAX_SUBCARRIERS}u");
    let _ = writeln!(s, "#define AQ_CSI_MAX_DATAGRAM_LEN {MAX_DATAGRAM_LEN}u");
    let _ = writeln!(s, "#define AQ_CONTROL_HEADER_LEN {}", control_offset::BODY);
    let _ = writeln!(s, "#define AQ_CONTROL_AUTH_LEN {CONTROL_AUTH_LEN}u");
    let _ = writeln!(
        s,
        "#define AQ_OTA_DEFAULT_CHUNK_SIZE {OTA_DEFAULT_CHUNK_SIZE}u"
    );
    let _ = writeln!(s, "#define AQ_OTA_DEFAULT_WINDOW {OTA_DEFAULT_WINDOW}u");
    let _ = writeln!(s, "#define AQ_OTA_MAX_CHUNK_SIZE {OTA_MAX_CHUNK_SIZE}u");
    let _ = writeln!(s);

    let _ = writeln!(s, "/* Variable-length CSI payload. */");
    let _ = writeln!(
        s,
        "/* Interleaved signed int8 I/Q, Q then I (imaginary first) per subcarrier; 2 bytes per subcarrier. */"
    );
    let _ = writeln!(s, "#define AQ_CSI_PAYLOAD_BYTES_PER_SUBCARRIER 2u");
    let _ = writeln!(
        s,
        "#define AQ_CSI_PAYLOAD_BYTES(n_subcarriers) (2u * (n_subcarriers))"
    );
    let _ = writeln!(
        s,
        "#define AQ_CSI_FRAME_SIZE(n_subcarriers) \\\n    (AQ_CSI_HEADER_LEN + AQ_CSI_BODY_FIXED_LEN + AQ_CSI_PAYLOAD_BYTES(n_subcarriers))"
    );
    let _ = writeln!(s);

    let _ = writeln!(s, "/* Control opcodes. */");
    emit_opcode(&mut s, "AQ_OP_JOIN_REQUEST", Opcode::JoinRequest);
    emit_opcode(&mut s, "AQ_OP_JOIN_ACK", Opcode::JoinAck);
    emit_opcode(&mut s, "AQ_OP_RESULT", Opcode::Result);
    emit_opcode(&mut s, "AQ_OP_STATUS", Opcode::Status);
    emit_opcode(&mut s, "AQ_OP_GET_CONFIG", Opcode::GetConfig);
    emit_opcode(&mut s, "AQ_OP_SET_CONFIG", Opcode::SetConfig);
    emit_opcode(&mut s, "AQ_OP_SET_CSI", Opcode::SetCsi);
    emit_opcode(&mut s, "AQ_OP_SYNC_PING", Opcode::SyncPing);
    emit_opcode(&mut s, "AQ_OP_SYNC_ECHO", Opcode::SyncEcho);
    emit_opcode(&mut s, "AQ_OP_REBOOT", Opcode::Reboot);
    emit_opcode(&mut s, "AQ_OP_IDENTIFY", Opcode::Identify);
    emit_opcode(&mut s, "AQ_OP_FACTORY_RESET", Opcode::FactoryReset);
    emit_opcode(&mut s, "AQ_OP_EVENT", Opcode::Event);
    emit_opcode(&mut s, "AQ_OP_OTA_BEGIN", Opcode::OtaBegin);
    emit_opcode(&mut s, "AQ_OP_OTA_CHUNK", Opcode::OtaChunk);
    emit_opcode(&mut s, "AQ_OP_OTA_ACK", Opcode::OtaAck);
    emit_opcode(&mut s, "AQ_OP_OTA_STATUS", Opcode::OtaStatus);
    emit_opcode(&mut s, "AQ_OP_OTA_END", Opcode::OtaEnd);
    emit_opcode(&mut s, "AQ_OP_OTA_ABORT", Opcode::OtaAbort);
    emit_opcode(&mut s, "AQ_OP_OTA_RESULT", Opcode::OtaResult);
    let _ = writeln!(s);

    let _ = writeln!(s, "/* CSI header field offsets. */");
    emit_offset(&mut s, "AQ_CSI_OFF_MAGIC", csi_offset::MAGIC);
    emit_offset(&mut s, "AQ_CSI_OFF_WIRE_MAJOR", csi_offset::WIRE_MAJOR);
    emit_offset(&mut s, "AQ_CSI_OFF_WIRE_MINOR", csi_offset::WIRE_MINOR);
    emit_offset(&mut s, "AQ_CSI_OFF_MESSAGE_TYPE", csi_offset::MESSAGE_TYPE);
    emit_offset(
        &mut s,
        "AQ_CSI_OFF_SUBCARRIER_FORMAT",
        csi_offset::SUBCARRIER_FORMAT,
    );
    emit_offset(&mut s, "AQ_CSI_OFF_NODE_ID", csi_offset::NODE_ID);
    emit_offset(&mut s, "AQ_CSI_OFF_PAYLOAD_LEN", csi_offset::PAYLOAD_LEN);
    emit_offset(&mut s, "AQ_CSI_OFF_BAND", csi_offset::BAND);
    emit_offset(&mut s, "AQ_CSI_OFF_CHANNEL", csi_offset::CHANNEL);
    emit_offset(
        &mut s,
        "AQ_CSI_OFF_BANDWIDTH_MHZ",
        csi_offset::BANDWIDTH_MHZ,
    );
    emit_offset(&mut s, "AQ_CSI_OFF_FLAGS", csi_offset::FLAGS);
    let _ = writeln!(s);

    let _ = writeln!(
        s,
        "/* CSI body field offsets (relative to the body start). */"
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_SEQUENCE",
        csi_body_offset::SEQUENCE,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_DEVICE_TIME_US",
        csi_body_offset::DEVICE_TIME_US,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_BOOT_EPOCH",
        csi_body_offset::BOOT_EPOCH,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_SUBCARRIER_OFFSET",
        csi_body_offset::SUBCARRIER_OFFSET,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_N_SUBCARRIERS",
        csi_body_offset::N_SUBCARRIERS,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_RSSI_DBM",
        csi_body_offset::RSSI_DBM,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_NOISE_FLOOR_DBM",
        csi_body_offset::NOISE_FLOOR_DBM,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_PHY_FLAGS",
        csi_body_offset::PHY_FLAGS,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_RESERVED",
        csi_body_offset::RESERVED,
    );
    emit_offset(
        &mut s,
        "AQ_CSI_BODY_OFF_SOURCE_MAC",
        csi_body_offset::SOURCE_MAC,
    );
    emit_offset(&mut s, "AQ_CSI_BODY_OFF_IQ", csi_body_offset::IQ);
    let _ = writeln!(s);

    let _ = writeln!(s, "/* Control header field offsets. */");
    emit_offset(&mut s, "AQ_CONTROL_OFF_MAGIC", control_offset::MAGIC);
    emit_offset(&mut s, "AQ_CONTROL_OFF_VERSION", control_offset::VERSION);
    emit_offset(&mut s, "AQ_CONTROL_OFF_OPCODE", control_offset::OPCODE);
    emit_offset(&mut s, "AQ_CONTROL_OFF_BODY_LEN", control_offset::BODY_LEN);
    emit_offset(
        &mut s,
        "AQ_CONTROL_OFF_REQUEST_ID",
        control_offset::REQUEST_ID,
    );
    emit_offset(&mut s, "AQ_CONTROL_OFF_BODY", control_offset::BODY);
    let _ = writeln!(s);

    let _ = writeln!(s, "/* Fixed layouts. Little-endian; packed. */");
    let _ = writeln!(s, "#pragma pack(push, 1)");
    let _ = writeln!(s, "typedef struct {{");
    let _ = writeln!(s, "    uint8_t  magic[4];");
    let _ = writeln!(s, "    uint8_t  wire_major;");
    let _ = writeln!(s, "    uint8_t  wire_minor;");
    let _ = writeln!(s, "    uint8_t  message_type;");
    let _ = writeln!(s, "    uint8_t  subcarrier_format;");
    let _ = writeln!(s, "    uint16_t node_id;");
    let _ = writeln!(s, "    uint16_t payload_len;");
    let _ = writeln!(s, "    uint8_t  band;");
    let _ = writeln!(s, "    uint8_t  channel;");
    let _ = writeln!(s, "    uint8_t  bandwidth_mhz;");
    let _ = writeln!(
        s,
        "    uint8_t  flags; /* bit0 = AQ_CSI_FLAG_FIRST_WORD_INVALID */"
    );
    let _ = writeln!(s, "}} aq_csi_header_t;");
    let _ = writeln!(s);
    let _ = writeln!(s, "typedef struct {{");
    let _ = writeln!(s, "    uint64_t sequence;");
    let _ = writeln!(s, "    uint64_t device_time_us;");
    let _ = writeln!(s, "    uint16_t boot_epoch;");
    let _ = writeln!(s, "    int16_t  subcarrier_offset;");
    let _ = writeln!(s, "    uint16_t n_subcarriers;");
    let _ = writeln!(s, "    int8_t   rssi_dbm;");
    let _ = writeln!(s, "    int8_t   noise_floor_dbm;");
    let _ = writeln!(s, "    uint16_t phy_flags;");
    let _ = writeln!(s, "    uint16_t reserved;");
    let _ = writeln!(
        s,
        "    uint8_t  source_mac[6]; /* the transmitting station's MAC address */"
    );
    let _ = writeln!(s, "}} aq_csi_body_fixed_t;");
    let _ = writeln!(s);
    let _ = writeln!(s, "typedef struct {{");
    let _ = writeln!(s, "    uint8_t  magic[4];");
    let _ = writeln!(s, "    uint8_t  version;");
    let _ = writeln!(s, "    uint8_t  opcode;");
    let _ = writeln!(s, "    uint16_t body_len;");
    let _ = writeln!(s, "    uint32_t request_id;");
    let _ = writeln!(s, "}} aq_control_header_t;");
    let _ = writeln!(s, "#pragma pack(pop)");
    let _ = writeln!(s);

    let _ = writeln!(
        s,
        "/* The variable-length AQCI body: the fixed fields, then the payload array. */"
    );
    let _ = writeln!(s, "typedef struct {{");
    let _ = writeln!(s, "    aq_csi_body_fixed_t fixed;");
    let _ = writeln!(
        s,
        "    int8_t payload[]; /* C99 flexible array member: interleaved Q,I (imaginary first) */"
    );
    let _ = writeln!(s, "}} aq_csi_body_t;");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "/* Accessors: the raw interleaved I/Q sample begins at payload[0]. */"
    );
    let _ = writeln!(s, "#define AQ_CSI_IQ(body) ((int8_t *)((body)->payload))");
    let _ = writeln!(s);

    let _ = writeln!(
        s,
        "_Static_assert(sizeof(aq_csi_header_t) == AQ_CSI_HEADER_LEN, \"AQCI header size\");"
    );
    let _ = writeln!(
        s,
        "_Static_assert(sizeof(aq_csi_body_fixed_t) == AQ_CSI_BODY_FIXED_LEN, \"AQCI body size\");"
    );
    let _ = writeln!(
        s,
        "_Static_assert(offsetof(aq_csi_body_t, payload) == AQ_CSI_BODY_FIXED_LEN, \"AQCI payload offset\");"
    );
    let _ = writeln!(s, "_Static_assert(sizeof(aq_control_header_t) == AQ_CONTROL_HEADER_LEN, \"AQCC header size\");");
    let _ = writeln!(s);
    let _ = writeln!(s, "#endif /* AQUILA_NODE_WIRE_H */");
    s
}

/// Emit four `#define`s for one ASCII magic, with a compile-time ASCII check.
fn emit_magic(s: &mut String, prefix: &str, magic: [u8; 4]) {
    for (i, byte) in magic.iter().enumerate() {
        let _ = writeln!(
            s,
            "#define {prefix}_{i} 0x{byte:02X}u /* '{}' */",
            *byte as char
        );
    }
}

/// Emit one opcode `#define`.
fn emit_opcode(s: &mut String, name: &str, opcode: Opcode) {
    let _ = writeln!(s, "#define {name} 0x{:02X}u", opcode.to_u8());
}

/// Emit one offset `#define`.
fn emit_offset(s: &mut String, name: &str, offset: usize) {
    let _ = writeln!(s, "#define {name} {offset}u");
}
